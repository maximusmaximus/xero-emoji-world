const toCodepoints = (g: string): string[] =>
  Array.from(g).map((c) => 'U+' + c.codePointAt(0)!.toString(16).toUpperCase().padStart(4, '0'));

const slugify = (n: string) => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

export const EMOJI_CATALOG: readonly EmojiInfo[] = ROWS.map(([glyph, name, category, roles, version]) => ({
  glyph, name, category, version,
  roles: roles.split(',') as EmojiRole[],
  codepoints: toCodepoints(glyph),
  slug: slugify(name),
}));

const BY_GLYPH = new Map(EMOJI_CATALOG.map((e) => [e.glyph, e]));
const BY_ROLE = new Map<EmojiRole, EmojiInfo[]>();
for (const e of EMOJI_CATALOG) for (const r of e.roles) {
  if (!BY_ROLE.has(r)) BY_ROLE.set(r, []);
  BY_ROLE.get(r)!.push(e);
}

export const emojiInfo = (glyph: string): EmojiInfo | undefined => BY_GLYPH.get(glyph);
export const emojisWithRole = (role: EmojiRole): EmojiInfo[] => BY_ROLE.get(role) ?? [];

/** External reference links shown in the close-up popup. */
export function emojiLinks(e: EmojiInfo): { label: string; url: string }[] {
  const hex = e.codepoints.map((c) => c.slice(2).toLowerCase());
  return [
    { label: 'Emojipedia', url: `https://emojipedia.org/${e.slug}` },
    { label: 'Unicode emoji list', url: 'https://unicode.org/emoji/charts/full-emoji-list.html' },
    { label: 'Unicode character', url: `https://www.compart.com/en/unicode/U+${hex[0]!.toUpperCase()}` },
    { label: 'Codepoints.net', url: `https://codepoints.net/U+${hex[0]!.toUpperCase()}` },
  ];
}
